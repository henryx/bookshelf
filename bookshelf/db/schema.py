from firebird.driver import Connection

__all__ = ["init_db"]

TABLES: dict[str, str] = {
    "USERS": """
        CREATE TABLE USERS (
            ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            EMAIL VARCHAR(254) NOT NULL UNIQUE,
            PASSWORD_HASH VARCHAR(255) NOT NULL,
            ROLE VARCHAR(16) DEFAULT 'REGULAR' NOT NULL,
            IS_LOCKED BOOLEAN DEFAULT FALSE NOT NULL,
            CONSTRAINT CHK_USERS_ROLE CHECK (ROLE IN ('ADMIN', 'REGULAR'))
        )
    """,
    "LOGIN_FAILURES": """
        CREATE TABLE LOGIN_FAILURES (
            ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            EMAIL VARCHAR(254) NOT NULL,
            ATTEMPTED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
        )
    """,
}


def init_db(conn: Connection) -> None:
    """
    Create missing tables. Safe to run more than once.
    """
    with conn.cursor() as cur:
        for name, ddl in TABLES.items():
            cur.execute(
                "SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = ?", (name,)
            )
            if cur.fetchone() is None:
                cur.execute(ddl)
    conn.commit()
